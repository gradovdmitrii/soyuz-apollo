from __future__ import annotations

import json
import re
from pathlib import Path

from .policy import ARCHIVE, POLICY, Policy, Rule

CLAUDE = ".claude/settings.json"
CODEX_CONFIG = ".codex/config.toml"
CODEX_RULES = ".codex/rules/s-a.rules"
PATHS = (CLAUDE, CODEX_CONFIG, CODEX_RULES)
HASH_MARKER = f"# GENERATED by s-a-satellite from {POLICY}. Do not edit. Edit the source, then run: python sa.py sync"
JSON_MARKER = (f"generated by s-a-satellite from {POLICY}; do not edit; "
               "local changes go to .claude/settings.local.json")
OWNER_HINT = {
    CLAUDE: "move your settings to .claude/settings.local.json and delete the file",
    CODEX_CONFIG: "move your settings to your user Codex config and delete the file",
    CODEX_RULES: "move your rules to your user Codex rules and delete the file",
}
CMDLET = re.compile(r"[A-Z][a-z]+-[A-Z][A-Za-z]+")


def render(root: Path, rules: Policy, archive: Path) -> dict[str, str]:
    """Fresh text of every adapter, keyed by its path relative to the root; same input, same bytes."""
    reads = [archive if item == ARCHIVE else Path(item) for item in rules.read_paths]
    return {CLAUDE: claude_settings(root, rules, reads), CODEX_CONFIG: codex_config(rules, reads),
            CODEX_RULES: codex_rules(rules)}


def claude_settings(root: Path, rules: Policy, reads: list[Path]) -> str:
    deny = [f"Read({claude_path(path)}/**)" for path in reads]
    deny += [f"Read({glob})" for glob in rules.read_globs]
    deny += [f"Edit(/{item}/**)" if (root / item).is_dir() else f"Edit(/{item})" for item in rules.write_paths]
    deny += [claude_command(rule) for rule in rules.deny]
    data = {"env": {"SA_ADAPTER": JSON_MARKER, "SA_AGENT": "claude-code"},
            "permissions": {"deny": deny, "ask": [claude_command(rule) for rule in rules.ask]}}
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def claude_command(rule: Rule) -> str:
    """Bash(<prefix> *); a PowerShell cmdlet takes its parameters in any order: PowerShell(<cmdlet> * <rest> *)."""
    head, rest = rule.prefix[0], " ".join(rule.prefix[1:])
    if CMDLET.fullmatch(head):
        return f"PowerShell({head} * {rest} *)" if rest else f"PowerShell({head} *)"
    return f"Bash({' '.join(rule.prefix)} *)"


def claude_path(path: Path) -> str:
    """Absolute path in the Claude Code rule form: //c/folder for C:\\folder, //folder for /folder."""
    posix = path.as_posix()
    if len(path.drive) == 2 and path.drive[1] == ":":
        return f"//{path.drive[0].lower()}{posix[2:]}"
    return "//" + posix.lstrip("/")


def codex_path(path: Path) -> str:
    """Absolute path as Codex is assumed to accept it on Windows: C:/folder (unverified, F9)."""
    posix = path.as_posix()
    return posix[0].upper() + posix[1:] if len(path.drive) == 2 and path.drive[1] == ":" else posix


def codex_config(rules: Policy, reads: list[Path]) -> str:
    lines = [HASH_MARKER, 'default_permissions = "s-a"', "", "[permissions.s-a]",
             'description = "Soyuz-Apollo installation: boundaries B1, B3, B6."', 'extends = ":workspace"', "",
             "[permissions.s-a.filesystem]"]
    lines += [f'{quote(codex_path(path))} = "deny"' for path in reads]
    lines += ["", '[permissions.s-a.filesystem.":workspace_roots"]']
    lines += [f'{quote(glob)} = "deny"' for glob in rules.read_globs]
    lines += [f'{quote(item)} = "read"' for item in rules.write_paths]
    return "\n".join(lines) + "\n"


def codex_rules(rules: Policy) -> str:
    lines = [HASH_MARKER]
    for decision, items in (("forbidden", rules.deny), ("prompt", rules.ask)):
        for rule in items:
            pattern = ", ".join(quote(word) for word in rule.prefix)
            lines.append(f"prefix_rule(pattern=[{pattern}], decision={quote(decision)}, "
                         f"justification={quote(rule.why)})")
    return "\n".join(lines) + "\n"


def quote(text: str) -> str:
    """A double-quoted string that TOML and Starlark both read back unchanged."""
    return json.dumps(text, ensure_ascii=False)
