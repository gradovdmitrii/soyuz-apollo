class Refused(Exception):
    """An expected refusal; the CLI prints the message and exits with 1."""


class GitError(Exception):
    """A git command failed unexpectedly; the CLI exits with 2."""


def say(text: str = "", err: bool = False) -> None:
    """Print English ASCII only; any other character is backslash-escaped."""
    stream = sys.stderr if err else sys.stdout
    print(text.encode("ascii", "backslashreplace").decode("ascii"), file=stream, flush=True)


def find_root() -> Path:
    """The installation root is the folder that holds sa.py, two levels above this package."""
    root = Path(__file__).resolve().parents[2]
    if not (root / ".agents" / "VERSION").is_file():
        raise Refused(f"{root} is not an installation root: .agents/VERSION is missing.")
    return root


def version(root: Path) -> str:
    lines = read_text(root / ".agents" / "VERSION").strip().splitlines()
    return lines[0].strip() if lines else "unknown"


def rel(root: Path, path: Path) -> str:
    return path.relative_to(root).as_posix()


def read_text(path: Path) -> str:
    with open(path, encoding="utf-8", newline="") as handle:
        return handle.read()


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def user_path(root: Path, arg: str) -> Path:
    """Resolve a user path against the current directory; it must lie inside the root."""
    path = (Path.cwd() / arg).resolve()
    if not path.is_relative_to(root):
        raise Refused(f"{arg}: outside the installation root {root}")
    return path


# --- git -------------------------------------------------------------------

# Local settings of every S-A repository; never written to the user's global Git config.
REPO_CONFIG = (("core.autocrlf", "false"), ("core.quotepath", "false"), ("core.longpaths", "true"))


def configure_repo(repo: Path) -> bool:
    """Write REPO_CONFIG into repo/.git/config; True if anything changed."""
    changed = False
    for key, value in REPO_CONFIG:
        if git("config", "--local", "--get", key, repo=repo).stdout.strip().lower() != value:
            git_ok("config", "--local", key, value, repo=repo)
            changed = True
    return changed


def has_git() -> bool:
    return shutil.which("git") is not None


def require_git() -> None:
    if not has_git():
        raise Refused("Git is not installed or not on PATH. Install Git, then retry.")


def git(*args: str, repo: Path | None = None, data: bytes | None = None) -> subprocess.CompletedProcess[str]:
    """Run git with an argument list; output is decoded as UTF-8."""
    cmd = ["git"] + (["-C", str(repo)] if repo is not None else []) + list(args)
    stdin = {"input": data} if data is not None else {"stdin": subprocess.DEVNULL}
    proc = subprocess.run(cmd, capture_output=True, **stdin)
    return subprocess.CompletedProcess(cmd, proc.returncode, proc.stdout.decode("utf-8", "replace"),
                                       proc.stderr.decode("utf-8", "replace"))


def git_ok(*args: str, repo: Path | None = None, data: bytes | None = None) -> str:
    result = git(*args, repo=repo, data=data)
    if result.returncode:
        raise GitError(f"git {args[0]} failed in {repo}: {git_message(result)}")
    return result.stdout.strip()


def git_message(result: subprocess.CompletedProcess[str]) -> str:
    lines = [line.strip() for line in (result.stderr + result.stdout).splitlines() if line.strip()]
    for line in lines:
        if line.startswith(("fatal:", "error:")):
            return line
    return lines[0] if lines else f"exit code {result.returncode}"


def git_config(root: Path) -> dict[str, str]:
    """Effective Git settings seen from the root (system and global scopes); the last value wins."""
    items = git("config", "--list", "-z", repo=root).stdout.split("\0")
    return {key.lower(): value.strip() for key, _, value in (item.partition("\n") for item in items if item)}


def missing_identity(root: Path, config: dict[str, str] | None = None) -> list[str]:
    config = git_config(root) if config is None else config
    return [key for key in ("user.name", "user.email") if not config.get(key)]


def identity_help(missing: list[str]) -> str:
    return (f"Git does not know who you are ({', '.join(missing)} not set). Run:\n"
            '  git config --global user.name "Your Name"\n'
            '  git config --global user.email "you@example.com"')


# --- guard -----------------------------------------------------------------

def guard_problems(root: Path) -> list[str]:
    problems = []
    if has_git() and git("rev-parse", "--is-inside-work-tree", repo=root).stdout.strip() == "true":
        problems.append(f"{root} is inside a Git work tree. An installation root must not be in a repository; "
                        "deploy install/ to a target folder first.")
    if not str(root).isascii() or " " in str(root):
        problems.append(f"the installation path {root} contains non-ASCII characters or spaces. "
                        "Move it to an ASCII kebab-case folder such as C:\\soyuz-apollo-november.")
    return problems


def guard(root: Path) -> None:
    """Refuse init and sync inside a Git work tree or on a non-ASCII path (STANDARD D3, ADR D14)."""
    require_git()
    problems = guard_problems(root)
    if problems:
        raise Refused("\n".join(f"Refusing to run: {problem}" for problem in problems))


def is_initialized(root: Path) -> bool:
    return (root / ".agents" / ".git").exists() and (root / ".agents" / "config" / "instance.toml").is_file()


# --- passports -------------------------------------------------------------

def split_passport(text: str) -> tuple[list[str] | None, str]:
    """Return (passport lines, body); the lines are None when the text has no front matter."""
    lines = text.splitlines(keepends=True)
    if lines and lines[0].rstrip("\r\n") == "---":
        for index in range(1, len(lines)):
            if lines[index].rstrip("\r\n") == "---":
                return [line.rstrip("\r\n") for line in lines[1:index]], "".join(lines[index + 1:])
    return None, text


def parse_passport(lines: list[str]) -> tuple[dict[str, str], dict[str, str], list[str]]:
    """Return (top-level fields, metadata fields, malformed lines)."""
    top: dict[str, str] = {}
    meta: dict[str, str] = {}
    bad: list[str] = []
    in_meta = False
    for line in lines:
        nested = line.startswith("  ")
        match = FIELD.fullmatch(line.strip())
        if match is None or (nested and not in_meta):
            bad.append(line)
            continue
        key, value = match.group(1), (match.group(2) or "").strip()
        if nested:
            meta[key] = value
        else:
            top[key] = value
            in_meta = key == "metadata" and not value
    return top, meta, bad


def python_passport(text: str) -> list[str] | None:
    """Passport lines from the module docstring of a Python script (STANDARD S9)."""
    try:
        doc = ast.get_docstring(ast.parse(text), clean=False)
    except (SyntaxError, ValueError):
        return None
    return None if doc is None else split_passport(doc.lstrip("\r\n"))[0]


# --- templates -------------------------------------------------------------

def template_body(root: Path, rel_path: str) -> list[str]:
    lines = read_text(root / rel_path).splitlines()
    marks = [line.strip() for line in lines]
    if TEMPLATE_START not in marks or TEMPLATE_END not in marks:
        raise RuntimeError(f"{rel_path} has no s-a:template-start/end markers")
    return lines[marks.index(TEMPLATE_START) + 1:marks.index(TEMPLATE_END)]


def render(root: Path, rel_path: str, values: dict[str, str]) -> str:
    out = []
    for line in template_body(root, rel_path):
        match = INCLUDE.fullmatch(line.strip())
        if match:
            out.append(include(root, match.group(1)))
            continue
        for key, value in values.items():
            line = line.replace("{{" + key + "}}", value)
        out.append(line)
    return "\n".join(out) + "\n"


def include(root: Path, spec: str) -> str:
    """Body of a file without its passport, headings demoted; `path#Section` takes one `## Section`."""
    path_part, _, section = spec.partition("#")
    path = (root / path_part).resolve()
    if not path.is_relative_to(root) or not path.is_file():
        raise RuntimeError(f"include not found inside the installation: {spec}")
    lines = split_passport(read_text(path))[1].splitlines()
    if section:
        starts = [i for i, line in enumerate(lines) if line.rstrip() == f"## {section}"]
        if not starts:
            raise RuntimeError(f"section not found for include: {spec}")
        stop = next((i for i in range(starts[0] + 1, len(lines)) if re.match(r"#{1,2}\s", lines[i])), len(lines))
        lines = lines[starts[0] + 1:stop]
    return "\n".join(demote(lines)).strip("\n")


def demote(lines: list[str]) -> list[str]:
    out, fenced = [], False
    for line in lines:
        if FENCE.match(line):
            fenced = not fenced
        elif not fenced and HEADING.match(line):
            line = "#" + line
        out.append(line)
    return out


def render_root(root: Path) -> str:
    return f"{ROOT_MARKER}\n\n{render(root, ROOT_TEMPLATE, {})}"


def render_project(root: Path, name: str, kind: str) -> str:
    return render(root, PROJECT_TEMPLATE, {"name": name, "kind": kind})


def header_span(text: str) -> tuple[int, int] | None:
    """Start and end offsets of the generated project header, markers included."""
    start = text.find(BEGIN)
    end = text.find(END, start) if start >= 0 else -1
    return (start, end + len(END)) if end >= 0 else None


def project_header(root: Path, name: str, kind: str) -> str:
    text = render_project(root, name, kind)
    span = header_span(text)
    if span is None:
        raise RuntimeError(f"{PROJECT_TEMPLATE} has no s-a:begin/s-a:end markers")
    return text[span[0]:span[1]]


def projects(root: Path) -> list[tuple[Path, str]]:
    """Folders in projects/ and system-projects/ with their kind."""
    found = []
    for area, kind in PROJECT_AREAS:
        base = root / area
        if base.is_dir():
            found += [(path, kind) for path in sorted(base.iterdir()) if path.is_dir() and not is_link(path)]
    return found


def skills(root: Path) -> dict[str, Path]:
    base = root / ".agents" / "skills"
    if not base.is_dir():
        return {}
    return {path.name: path for path in sorted(base.iterdir())
            if path.is_dir() and not is_link(path) and (path / "SKILL.md").is_file()}


# --- links and walking -----------------------------------------------------

def link_target(path: Path) -> str | None:
    """Target of a symlink or junction; None for anything else."""
    try:
        target = os.readlink(path)
    except (OSError, ValueError):
        return None
    for prefix, replacement in (("\\\\?\\UNC\\", "\\\\"), ("\\\\?\\", "")):
        if target.startswith(prefix):
            return replacement + target[len(prefix):]
    return target


def is_link(path: Path) -> bool:
    return os.path.islink(path) or link_target(path) is not None


def points_to(link: Path, target: Path) -> bool:
    raw = link_target(link)
    if raw is None:
        return False
    resolved = Path(raw) if Path(raw).is_absolute() else link.parent / raw
    return os.path.normcase(os.path.normpath(resolved)) == os.path.normcase(os.path.normpath(target))


def make_link(link: Path, target: Path) -> None:
    link.parent.mkdir(parents=True, exist_ok=True)
    if os.name == "nt":
        proc = subprocess.run(["cmd", "/c", "mklink", "/J", str(link), str(target)],
                              capture_output=True, stdin=subprocess.DEVNULL)
        if proc.returncode:
            raise RuntimeError(f"mklink /J failed for {link}")
    else:
        os.symlink(target, link, target_is_directory=True)


def remove_link(link: Path) -> None:
    """Remove a symlink or junction; never a real folder."""
    if os.path.islink(link):
        os.unlink(link)
    elif link_target(link) is not None:
        os.rmdir(link)
    else:
        raise RuntimeError(f"refusing to remove {link}: it is not a link")


def walk(folder: Path, skip: tuple[str, ...] = (".git",),
         keep: Callable[[Path], bool] | None = None) -> Iterator[tuple[Path, str]]:
    """Yield (path, kind) below folder; kind is dir, file or link. Links are never followed.

    Entries named in skip, or rejected by keep, are left out together with everything below them.
    """
    try:
        with os.scandir(folder) as handle:
            entries = sorted(handle, key=lambda entry: entry.name)
    except OSError:
        return
    for entry in entries:
        path = Path(entry.path)
        if entry.name in skip or (keep is not None and not keep(path)):
            continue
        is_dir = entry.is_dir(follow_symlinks=False)
        if entry.is_symlink() or (is_dir and link_target(path) is not None):
            yield path, "link"
        elif is_dir:
            yield path, "dir"
            yield from walk(path, skip, keep)
        else:
            yield path, "file"
