"""
---
name: s-a-ownership
description: Ownership rule of STANDARD S13 - classifies every target that init and sync write as absent, generated, mixed or owner.
type: script
inputs: none; imported by init, sync and doctor
outputs: none
side_effects: none on import; mark_managed writes one key into a repository's local .git/config
destructive: false
requires_owner: false
version: 0.2.0
origin: Soyuz-Apollo Framework | by Dmitrii Gradov | 2026-10
---
"""

from __future__ import annotations

import json
from pathlib import Path

from . import common

ABSENT, GENERATED, MIXED, OWNER = "absent", "generated", "mixed", "owner"
WRITABLE = (ABSENT, GENERATED)
MANAGED_KEY = "soyuz-apollo.managed"
MARKERS = ("<!-- GENERATED by s-a-satellite from ", "# GENERATED by s-a-satellite from ")
JSON_MARKER = "generated by s-a-satellite from "


def state(root: Path, path: Path) -> str:
    """S13 state of a write target: absent, generated (S-A can prove it manages it), mixed, or owner.

    Proofs: a link whose target is .agents/skills/<same name>; a folder whose repository has
    soyuz-apollo.managed = true in its local .git/config; a file whose first line is the GENERATED
    marker (in JSON the field env.SA_ADAPTER); a file with the s-a:begin and s-a:end markers.
    Everything else is owner content, also a link or a file standing between the root and the path.
    """
    if blocked(root, path):
        return OWNER
    if common.is_link(path):
        return GENERATED if common.points_to(path, root / ".agents" / "skills" / path.name) else OWNER
    if not path.exists():
        return ABSENT
    if path.is_dir():
        return GENERATED if repo_managed(path) else OWNER
    try:
        text = common.read_text(path)
    except (OSError, UnicodeDecodeError):
        return OWNER
    if has_marker(path, text):
        return GENERATED
    return MIXED if common.header_span(text) is not None else OWNER


def blocked(root: Path, path: Path) -> bool:
    """True when a link or a non-folder stands between the root and the path; S-A never writes through it."""
    for parent in path.parents:
        if parent == root or not parent.is_relative_to(root):
            return False
        if common.is_link(parent) or (parent.exists() and not parent.is_dir()):
            return True
    return False


def has_marker(path: Path, text: str) -> bool:
    if path.suffix == ".json":
        try:
            env = json.loads(text).get("env")
        except (ValueError, RecursionError, AttributeError):
            return False
        marker = env.get("SA_ADAPTER") if isinstance(env, dict) else None
        return isinstance(marker, str) and marker.startswith(JSON_MARKER)
    return text.startswith(MARKERS)


def repo_managed(repo: Path) -> bool:
    """Only the repository's own local config counts; a global soyuz-apollo.managed proves nothing."""
    if not (repo / ".git").exists() or not common.has_git():
        return False
    result = common.git("config", "--local", "--type=bool", "--get", MANAGED_KEY, repo=repo)
    return result.returncode == 0 and result.stdout.strip() == "true"


def mark_managed(repo: Path) -> None:
    common.git_ok("config", "--local", MANAGED_KEY, "true", repo=repo)
